"""Measure transparent padding for CSS layout; never modify the source artwork."""
import json
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1] / 'dist'
files = sorted((root / 'assets').glob('[0-9]*.png'))
files += sorted((root / 'assets/world').glob('portrait-*.png'))
portraits = {}
for file in files:
    image = Image.open(file).convert('RGBA')
    left, top, right, bottom = image.getbbox()
    scale = 32 / max(right - left, bottom - top)
    portraits[file.relative_to(root).as_posix()] = {
        'width': round(image.width * scale, 3),
        'height': round(image.height * scale, 3),
        'x': round((image.width - left - right) * scale / 2, 3),
        'y': round((image.height - top - bottom) * scale / 2, 3),
    }
output = root / 'ui/ribbon-portraits.mjs'
output.write_text('// Generated by scripts/measure-ribbon-portraits.py. Source PNGs stay unchanged.\n'
                  + 'export const RIBBON_PORTRAITS=' + json.dumps(portraits, indent=1) + ';\n', encoding='utf-8')
print(f'Measured {len(portraits)} portraits for centered ribbon layout.')
